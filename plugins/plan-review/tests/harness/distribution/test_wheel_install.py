"""WheelInstall: a tool that plan-review installs itself, from the wheel of a release."""

import subprocess
from pathlib import Path, PurePath
from typing import Any

import pytest

from plan_review.harness.distribution import SelfInstall, ToolInstall, WheelInstall, releases, wheel


def make(tmp_path: Path, key: str = "other") -> WheelInstall:
    source = tmp_path / "source"
    (source / "a").mkdir(parents=True, exist_ok=True)
    (source / "a" / "one.txt").write_text("generated by M: one")
    (source / "two.txt").write_text("generated by M: two")

    def targets(relative: PurePath) -> Path:
        return tmp_path / "home" / relative

    return WheelInstall(
        key=key, tool_name="Xtool", files=source, targets=targets, mark="generated by M"
    )


def test_wheel_install_copies_its_files_to_the_targets_it_is_given(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    install = make(tmp_path)
    mine = tmp_path / "home" / "two.txt"
    mine.parent.mkdir()
    mine.write_text("generated by M: older")  # its own older file may be replaced

    assert install.install() == 0

    assert (tmp_path / "home" / "a" / "one.txt").read_text() == "generated by M: one"
    assert mine.read_text() == "generated by M: two"
    assert f"wrote {(tmp_path / 'home' / 'two.txt').as_posix()}" in capsys.readouterr().out


def test_wheel_install_leaves_a_file_that_is_not_its_own(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    install = make(tmp_path)
    theirs = tmp_path / "home" / "two.txt"
    theirs.parent.mkdir()
    theirs.write_text("mine")

    assert install.install() == 1

    assert theirs.read_text() == "mine"
    assert not (tmp_path / "home" / "a").exists()
    assert "not written by plan-review; left alone" in capsys.readouterr().err


def test_wheel_install_with_no_files_says_so(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    empty = tmp_path / "empty"
    empty.mkdir()
    install = WheelInstall(
        key="other", tool_name="Xtool", files=empty, targets=lambda r: tmp_path / r, mark="M"
    )

    assert install.install() == 1
    assert "Xtool files are missing" in capsys.readouterr().err


def test_wheel_install_upgrade_ends_by_installing_its_own_tool(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    calls: list[list[str]] = []

    def run(argv: list[str], **_: object) -> subprocess.CompletedProcess[str]:
        calls.append(argv)
        return subprocess.CompletedProcess(argv, 0, stdout="")

    releases_list: list[dict[str, Any]] = [
        {
            "tag_name": "plan-review--v1.0.0",
            "assets": [{"name": "plan_review-1.0.0-py3-none-any.whl", "browser_download_url": "U"}],
        }
    ]
    monkeypatch.setattr(releases, "fetch_releases", lambda: releases_list)
    monkeypatch.setattr(wheel.shutil, "which", lambda name: f"/bin/{name}")
    monkeypatch.setattr(wheel.subprocess, "run", run)
    install = make(tmp_path)

    assert install.upgrade() == 0

    assert calls[0] == ["/bin/uv", "tool", "install", "--force", "U"]
    assert calls[-1] == ["/bin/plan-review", "install", "other"]
    assert install.upgrade_commands()[-1] == "plan-review install other"
    assert isinstance(install, SelfInstall)
    assert not isinstance(install, ToolInstall)
    assert not hasattr(install, "available")


def test_wheel_install_knows_a_uv_tool_copy_only_with_its_files(tmp_path: Path) -> None:
    tool = tmp_path / "tools" / "plan-review"
    root = tool / "lib" / "python3.15"
    root.mkdir(parents=True)
    (tool / "uv-receipt.toml").write_text("[tool]\n")
    install = make(tmp_path)

    assert not install.installed_at(root)  # none of its files are in place

    theirs = tmp_path / "home" / "two.txt"
    theirs.parent.mkdir()
    theirs.write_text("not mine")

    assert not install.installed_at(root)  # a file without the mark does not count

    theirs.write_text("generated by M: older")

    assert install.installed_at(root)


def test_wheel_install_does_not_know_files_without_a_uv_tool_copy(tmp_path: Path) -> None:
    install = make(tmp_path)
    mine = tmp_path / "home" / "a" / "one.txt"
    mine.parent.mkdir(parents=True)
    mine.write_text("generated by M: one")

    assert not install.installed_at(tmp_path / "elsewhere")


def test_wheel_install_skips_a_file_that_is_not_text(tmp_path: Path) -> None:
    tool = tmp_path / "tool"
    (tool / "lib").mkdir(parents=True)
    (tool / "uv-receipt.toml").write_text("[tool]\n")
    install = make(tmp_path)
    (tmp_path / "home").mkdir()
    (tmp_path / "home" / "two.txt").write_bytes(b"\xff\xfe")

    assert not install.installed_at(tool / "lib")
