"""Everything specific to OpenAI Codex.

Codex has no plugin to install here: the ship skill goes in `~/.agents/skills/` and the four
agents in `~/.codex/agents/` (or `$CODEX_HOME/agents/`). `plan-review` itself is installed with
`uv tool install` from the wheel of a release, so an upgrade installs the newest wheel and then
writes those files again.
"""

import os
from pathlib import Path, PurePath, PurePosixPath

from plan_review.harness.agent_files import TomlAgents
from plan_review.harness.distribution import WheelInstall
from plan_review.harness.harness import Harness
from plan_review.harness.waiting import PollingWaiting
from plan_review.harness.wording import Wording

MARK = "generated by plan-review"  # in every file this adapter writes: it may replace those

# Inside the package, so the wheel carries them.
PACKAGE_FILES = PurePosixPath("src/plan_review/harness/adapters/codex_files")
FILES = Path(__file__).parent / "codex_files"

SHIP_POLICY = (
    f"# {MARK}: edit workflow/, not this file\n"
    "# $ship runs only when asked for, as disable-model-invocation does in Claude Code\n"
    "policy:\n"
    "  allow_implicit_invocation: false\n"
)


def home_target(relative: PurePath) -> Path:
    """Where a file under codex_files/ goes: skills in ~/.agents, agents in the Codex home."""
    home = Path.home()
    if relative.parts[0] == "skills":
        return home / ".agents" / relative
    return Path(os.environ.get("CODEX_HOME") or home / ".codex") / relative


KEY = "codex"
NAME = "Codex"

HARNESS = Harness(
    key=KEY,
    name=NAME,
    wording=Wording(
        arguments="<what follows $ship>",
        agent_prefix="plan-review-",
        agent_override=".codex/agents/<name>.toml",
        rules_file="AGENTS.md",
        rules_also="",
        harness_folder=".codex/",
        skill_tool="(invoke it as `$grilling`)",
    ),
    agent_files=TomlAgents(
        folder=PACKAGE_FILES,
        mark=MARK,
        extra_files={PurePosixPath("skills/ship/agents/openai.yaml"): SHIP_POLICY},
    ),
    distribution=WheelInstall(key=KEY, tool_name=NAME, files=FILES, targets=home_target, mark=MARK),
    waiting=PollingWaiting(),
)
