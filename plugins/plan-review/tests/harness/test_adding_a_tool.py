"""Adding a tool is one file in adapters/: nothing else names it."""

import ast
import subprocess
import sys
from collections.abc import Iterator
from pathlib import Path

import pytest
from conftest import PLUGIN

from plan_review.cli import main
from plan_review.harness import adapters, generate, upgrade
from plan_review.harness.adapters import all_adapters
from plan_review.harness.distribution import marketplace

SAMPLES = PLUGIN / "tests" / "fixtures" / "adapters"


@pytest.fixture
def sample_tool(monkeypatch: pytest.MonkeyPatch) -> Iterator[None]:
    """Drop the sample file into adapters/: add its folder to the package's search path."""
    monkeypatch.setattr(adapters, "__path__", [*adapters.__path__, str(SAMPLES)])
    yield
    sys.modules.pop("plan_review.harness.adapters.a_sample_tool", None)


def test_the_tools_are_found_in_the_adapters_folder_in_file_name_order() -> None:
    assert [h.key for h in all_adapters()] == ["claude-code", "codex"]


def test_tools_in_two_folders_are_ordered_by_file_name_across_both(sample_tool: None) -> None:
    assert [h.key for h in all_adapters()] == ["sample-tool", "claude-code", "codex"]


def test_the_adapters_package_names_no_tool() -> None:
    tree = ast.parse(Path(adapters.__file__ or "").read_text("utf-8"))
    names = [
        *(n.module or "" for n in ast.walk(tree) if isinstance(n, ast.ImportFrom)),
        *(
            a.name
            for n in ast.walk(tree)
            if isinstance(n, ast.ImportFrom | ast.Import)
            for a in n.names
        ),
    ]

    assert not [n for n in names if "claude_code" in n or "codex" in n]


def write_workflow(root: Path) -> None:
    (root / "workflow" / "agents").mkdir(parents=True)
    (root / "workflow" / "ship.md").write_text("---\nname: ship\ndescription: S\n---\n\n# Ship\n")
    for name in ("architect", "implementer", "test-reviewer", "code-reviewer"):
        (root / "workflow" / "agents" / f"{name}.md").write_text(
            f"---\nname: {name}\ndescription: D\n---\n\nRules: {{{{rules_file}}}}\n"
        )


def test_a_new_tool_in_its_own_file_is_generated(sample_tool: None, tmp_path: Path) -> None:
    write_workflow(tmp_path)

    files = generate.expected_files(tmp_path)

    skill = tmp_path / "sample_files" / "skills" / "ship" / "SKILL.md"
    assert skill in files
    assert b"generated by sample" in files[skill]
    assert tmp_path / "skills" / "ship" / "SKILL.md" in files  # next to Claude Code's
    assert tmp_path / "src/plan_review/harness/adapters/codex_files/skills/ship/SKILL.md" in files
    assert b"SAMPLE.md" in files[tmp_path / "sample_files" / "agents" / "sample-architect.toml"]


def test_a_new_tool_in_its_own_file_can_be_installed(
    sample_tool: None, capsys: pytest.CaptureFixture[str]
) -> None:
    assert main(["install", "sample-tool"]) == 2

    assert "`sampletool plugin install plan-review@sample-market`" in capsys.readouterr().out


def test_a_new_tool_in_its_own_file_is_upgraded(
    sample_tool: None, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    (tmp_path / ".sample-plugin").mkdir()
    (tmp_path / ".sample-plugin" / "plugin.json").write_text("{}")
    calls: list[list[str]] = []

    def run(argv: list[str], **_: object) -> subprocess.CompletedProcess[str]:
        calls.append(argv)
        return subprocess.CompletedProcess(argv, 0)

    monkeypatch.setattr(upgrade, "PACKAGE_ROOT", tmp_path)
    monkeypatch.setattr(marketplace.shutil, "which", lambda name: f"/bin/{name}")
    monkeypatch.setattr(marketplace.subprocess, "run", run)

    assert main(["upgrade"]) == 0

    assert calls == [
        ["/bin/sampletool", "plugin", "marketplace", "update", "sample-market"],
        ["/bin/sampletool", "plugin", "update", "plan-review@sample-market"],
    ]
