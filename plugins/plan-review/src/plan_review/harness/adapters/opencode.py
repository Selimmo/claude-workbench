"""Everything specific to opencode.

opencode has no plugin to install here: the /plan-review-ship command and the four agents are
Markdown files in `~/.config/opencode/` (or `$XDG_CONFIG_HOME/opencode/`). `plan-review` itself is
installed with `uv tool install` from the wheel of a release. opencode's shell stops a command
after 2 minutes, so the agent waits for the owner in slices of 100 seconds.
"""

import json
import os
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path, PurePath, PurePosixPath

from plan_review.harness.distribution import WheelInstall
from plan_review.harness.harness import Harness
from plan_review.harness.waiting import PollingWaiting
from plan_review.harness.wording import Wording
from plan_review.harness.workflow import Workflow, fill

KEY = "opencode"
NAME = "opencode"
MARK = "generated by plan-review"

PACKAGE_FILES = PurePosixPath("src/plan_review/harness/adapters/opencode_files")
FILES = Path(__file__).parent / "opencode_files"


# The Codex `ship` skill in ~/.agents/skills is listed by opencode too: keep the model off it.
SHIP_PREAMBLE = (
    "Follow only the text below. Do not load a skill named `ship`, even if one is listed: "
    "this command is the whole workflow.\n\n"
)

_DENY_SUBAGENTS = (("subagent", "*", "deny"),)
_DENY_EDITS = (("edit", "*", "deny"),)
# Who may not start other agents, and who may not change files.
AGENT_PERMISSIONS: Mapping[str, tuple[tuple[str, str, str], ...]] = {
    "architect": _DENY_SUBAGENTS,
    "implementer": _DENY_SUBAGENTS,
    "test-reviewer": _DENY_SUBAGENTS + _DENY_EDITS,
    "code-reviewer": _DENY_SUBAGENTS + _DENY_EDITS,
}


def _frontmatter(lines: list[str]) -> str:
    return "---\n" + "".join(f"{line}\n" for line in lines) + "---\n"


@dataclass(frozen=True)
class OpencodeMarkdown:
    """The /plan-review-ship command and the agents, as opencode reads them. Every field of the
    frontmatter that holds text is JSON-quoted, so a ` #` or `: ` in it stays text."""

    folder: PurePosixPath
    mark: str

    def _mark(self) -> str:
        return f"\n<!-- {self.mark}: edit workflow/, not this file -->\n"

    def files(self, workflow: Workflow, slots: Mapping[str, str]) -> dict[PurePosixPath, str]:
        ship = workflow.ship
        files = {
            self.folder / "commands/plan-review-ship.md": _frontmatter(
                [
                    f"description: {json.dumps(ship.description)}",
                    "agent: build",
                    "subagent: false",
                ]
            )
            + self._mark()
            + SHIP_PREAMBLE
            + fill(ship.body, slots)
        }
        for name, agent in workflow.agents.items():
            rules = [
                line
                for action, resource, effect in AGENT_PERMISSIONS[name]
                for line in (
                    f"  - action: {action}",
                    f"    resource: {json.dumps(resource)}",
                    f"    effect: {effect}",
                )
            ]
            header = _frontmatter(
                [
                    f"description: {json.dumps(agent.description)}",
                    "mode: subagent",
                    "permissions:",
                    *rules,
                ]
            )
            files[self.folder / f"agents/{slots['agent_prefix']}{name}.md"] = (
                header + self._mark() + fill(agent.body, slots)
            )
        return files


def config_home() -> Path:
    """opencode's folder: under `$XDG_CONFIG_HOME` when it is set and not empty."""
    base = os.environ.get("XDG_CONFIG_HOME") or Path.home() / ".config"
    return Path(base) / "opencode"


def home_target(relative: PurePath) -> Path:
    """Where a file under opencode_files/ goes."""
    return config_home() / relative


HARNESS = Harness(
    key=KEY,
    name=NAME,
    wording=Wording(
        arguments="$ARGUMENTS",
        agent_prefix="plan-review-",
        agent_override=".opencode/agents/<name>.md",
        rules_file="AGENTS.md",
        rules_also="",
        harness_folder=".opencode/",
        skill_tool="(load it with the `skill` tool)",
    ),
    agent_files=OpencodeMarkdown(folder=PACKAGE_FILES, mark=MARK),
    distribution=WheelInstall(key=KEY, tool_name=NAME, files=FILES, targets=home_target, mark=MARK),
    waiting=PollingWaiting(wait_seconds=100),
)
